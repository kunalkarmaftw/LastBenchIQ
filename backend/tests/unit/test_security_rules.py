"""Tests that enforce architectural rules rather than behaviour.

These are the project's structural guardrails. They fail when future code — written
by a person or generated by an AI — violates a decision recorded in the docs. A rule
that lives only in a markdown file erodes; a rule with a failing test does not.
"""

import pytest

from app.core.config import Settings
from app.models.base import TimestampMixin, UserOwnedMixin

pytestmark = pytest.mark.unit


def test_user_owned_mixin_provides_user_id() -> None:
    """Step 3 audit: user-owned tables must carry user_id, not rely on a join."""
    assert hasattr(UserOwnedMixin, "user_id")


def test_timestamp_mixin_provides_created_at() -> None:
    assert hasattr(TimestampMixin, "created_at")


def test_production_rejects_the_development_secret() -> None:
    """A deploy must never silently run with the throwaway dev key."""
    settings = Settings(environment="production", llm_api_key="real-key")
    with pytest.raises(RuntimeError, match="SECRET_KEY"):
        settings.validate_production()


def test_production_requires_an_llm_key() -> None:
    settings = Settings(environment="production", secret_key="a-real-secret")
    with pytest.raises(RuntimeError, match="LLM_API_KEY"):
        settings.validate_production()


def test_local_environment_starts_without_secrets() -> None:
    """Local development must not need production credentials."""
    Settings(environment="local").validate_production()


def test_analysis_thresholds_match_the_documented_minimum() -> None:
    """DATA_MODEL minimum-data rule: >=3 papers and >=50 questions.

    Clustering below this produces noise, so the API returns `insufficient_data`
    instead of bad topics. If someone lowers these, this test should make them
    justify it.
    """
    settings = Settings()
    assert settings.min_papers_for_analysis == 3
    assert settings.min_questions_for_analysis == 50


def test_agent_loop_is_bounded() -> None:
    """TECH_SPEC §5.3: an unbounded agent loop is a hang and a bill."""
    settings = Settings()
    assert 0 < settings.agent_max_iterations <= 10
    assert 0 < settings.agent_timeout_seconds <= 300
